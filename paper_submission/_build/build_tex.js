// Writes the LaTeX version of the 2D paper (Springer Nature template sn-jnl, two columns) from
// content_bmc2d.js, the same source as the Word version.
// Usage: node build_tex.js <out.tex> [sub]
//   sub: BMC Medical Imaging submission (one column, double spacing, line numbers, unnumbered headings)
const fs = require('fs');
const content = require('./content_bmc2d.js');

const OUT = process.argv[2];
const SUB = process.argv[3] === 'sub';
const UNI = {
  '×': '$\\times$', '±': '$\\pm$', '−': '$-$', '≥': '$\\geq$', '≤': '$\\leq$', '°': '$^\\circ$', 'μ': '$\\mu$',
  'σ': '$\\sigma$', 'ρ': '$\\rho$', '→': '$\\rightarrow$', '≈': '$\\approx$', '’': "'", '‘': '`', '“': '``', '”': "''",
  '–': '--', '—': '---', 'ë': '\\"e', 'ö': '\\"o', 'ü': '\\"u',
};

function esc(text) {
  // URLs first (kept verbatim inside \url), then LaTeX specials, then Unicode
  return text.split(/(https?:\/\/\S+[^\s.,;)])/).map((part, i) => {
    if (i % 2 === 1) return `\\url{${part}}`;
    return part
      .replace(/\\/g, '\\textbackslash{}')
      .replace(/([&%$#_{}])/g, '\\$1')
      .replace(/~/g, '\\textasciitilde{}')
      .replace(/\^/g, '\\textasciicircum{}')
      .replace(/./gu, (c) => UNI[c] || c);
  }).join('');
}

function tex(text) {
  const re = /(\[\[cite:[^\]]+\]\]|\{TBD[^}]*\}|\*\*[^*]+\*\*|\*[^*]+\*|_\{[^}]+\}|\^\{[^}]+\})/g;
  let out = '', last = 0, m;
  while ((m = re.exec(text))) {
    out += esc(text.slice(last, m.index));
    const t = m[0];
    if (t.startsWith('[[cite:')) out += `~\\cite{${t.slice(7, -2).split(',').map((s) => s.trim()).join(',')}}`;
    else if (t.startsWith('{TBD')) out += `\\tbd{${esc(t.slice(1, -1))}}`;
    else if (t.startsWith('**')) out += `\\textbf{${tex(t.slice(2, -2))}}`;
    else if (t.startsWith('*')) out += `\\emph{${tex(t.slice(1, -1))}}`;
    else if (t.startsWith('_{')) out += `\\textsubscript{${esc(t.slice(2, -1))}}`;
    else if (t.startsWith('^{')) out += `\\textsuperscript{${esc(t.slice(2, -1))}}`;
    last = m.index + t.length;
  }
  return (out + esc(text.slice(last))).replace(/ ~\\cite/g, '~\\cite');
}

let fig = 0, tab = 0;
function block(b) {
  if (b.h1) return `\\section{${tex(b.h1)}}\\label{sec:${b.h1.toLowerCase().replace(/\W+/g, '')}}\n`;
  if (b.h2) return `\\subsection{${tex(b.h2)}}\n`;
  if (b.h) return `\\section*{${tex(b.h)}}\n`;
  if (b.p !== undefined) return `${tex(b.p)}\n`;
  if (b.ol) return `\\begin{enumerate}\n${b.ol.map((x) => `\\item ${tex(x)}`).join('\n')}\n\\end{enumerate}\n`;
  if (b.ul) return `\\begin{itemize}\n${b.ul.map((x) => `\\item ${tex(x)}`).join('\n')}\n\\end{itemize}\n`;
  if (b.figure) {
    fig++;
    const env = b.wide && !SUB ? 'figure*' : 'figure';
    const w = b.wide || SUB ? '\\textwidth' : '\\columnwidth';
    const cap = b.figure.title ? `\\textbf{${tex(b.figure.title)}.} ${tex(b.figure.caption)}` : tex(b.figure.caption);
    return `\\begin{${env}}[!t]\n\\centering\n\\includegraphics[width=${w}]{${b.figure.path.replace(/\.png$/, '.pdf')}}\n\\caption{${cap}}\\label{fig${fig}}\n\\end{${env}}\n`;
  }
  if (b.table) {
    tab++;
    const t = b.table;
    const env = b.wide && !SUB ? 'table*' : 'table';
    const n = t.widths.length;
    const cols = 'l' + 'c'.repeat(n - 1);
    const row = (cells) => cells.map((c) => {
      const cell = typeof c === 'string' ? { t: c } : c;
      return cell.span ? `\\multicolumn{${cell.span}}{c}{${tex(cell.t)}}` : tex(cell.t);
    }).join(' & ') + ' \\\\';
    const head = t.header.map(row).join('\n');
    const body = t.rows.map(row).join('\n');
    const note = t.note ? `\\footnotetext{${tex(t.note)}}\n` : '';
    return `\\begin{${env}}[!t]\n\\caption{${tex(t.title || t.caption)}}\\label{tab${tab}}\n\\centering\\footnotesize\n` +
      `\\begin{tabular}{${cols}}\n\\toprule\n${head}\n\\midrule\n${body}\n\\botrule\n\\end{tabular}\n${note}\\end{${env}}\n`;
  }
  throw new Error('unknown block ' + JSON.stringify(b).slice(0, 80));
}

const m = content.meta;
const name = (a) => { const p = a.name.split(' '); return `\\fnm{${p.slice(0, -1).join(' ')}} \\sur{${p[p.length - 1]}}`; };
const authors = m.authors.map((a) => `\\author${a.corresponding ? '*' : ''}[${a.affil.join(',')}]{${name(a)}}${a.email ? `\\email{${a.email}}` : ''}`).join('\n');
const affils = content.sn.affils.map((x, i) =>
  `\\affil${i === 0 ? '*' : ''}[${i + 1}]{\\orgdiv{${esc(x.orgdiv)}}, \\orgname{${esc(x.orgname)}}, \\orgaddress{\\city{${esc(x.city)}}, \\country{${esc(x.country)}}}}`).join('\n');
const abstract = m.abstract.map(([l, t]) => `\\textbf{${l}:} ${tex(t)}`).join('\n\n');

const addFiles = (content.additionalFiles || []).map((a) => `\\bmhead{${esc(a.name)} (${esc(a.format)})}\n\\emph{${tex(a.title)}.} ${tex(a.description)}\n`).join('\n');
const doc = `%% Generated by paper_submission/_build/build_tex.js from content_bmc2d.js -- edit the content file,
%% not this file. Springer Nature LaTeX template (sn-jnl, recommended by BMC Medical Imaging), Vancouver
%% numbered references. ${SUB ? 'Submission layout: one column, double spacing, line numbers.' : 'Two-column layout (iicol).'}
%% BMC compiles submissions with pdfLaTeX (TeX Live 2021). Upload this file, references.bib and figures/.
\\documentclass[pdflatex,sn-vancouver-num${SUB ? '' : ',iicol'}]{sn-jnl}

\\usepackage{graphicx}%
\\usepackage{multirow}%
\\usepackage{amsmath,amssymb,amsfonts}%
\\usepackage{amsthm}%
\\usepackage{mathrsfs}%
\\usepackage[title]{appendix}%
\\usepackage{xcolor}%
\\usepackage{textcomp}%
\\usepackage{manyfoot}%
\\usepackage{booktabs}%
\\usepackage{url}%
\\raggedbottom
\\newcommand{\\tbd}[1]{\\textcolor{red}{\\textbf{[#1]}}}
${SUB ? '\\usepackage{lineno}\n\\linenumbers\n\\usepackage{setspace}\n\\doublespacing\n\\setcounter{secnumdepth}{0}\n' : ''}
\\begin{document}

\\title[${esc(m.running)}]{${esc(m.title)}}

${authors}

${affils}

\\abstract{${abstract}}

\\keywords{${m.keywords.map(esc).join(', ')}}

\\maketitle

${content.body.map(block).join('\n')}
\\backmatter

${SUB ? '' : `\\bmhead{Supplementary information}\n${tex(content.sn.supplementary)}\n\n\\bmhead{Acknowledgements}\n${tex(content.sn.acknowledgements)}\n\n`}\\bmhead{Abbreviations}
${content.abbreviations.map(([a, b]) => `${esc(a)}, ${esc(b)}`).join('; ')}.

\\section*{Declarations}
${SUB ? content.declarations.map(([h, t]) => `\\bmhead{${esc(h)}}\n${tex(t)}\n`).join('\n')
  : `\\begin{itemize}\n${content.sn.declarations.map(([h, t]) => `\\item ${esc(h)}: ${tex(t)}`).join('\n')}\n\\end{itemize}\n`}
\\bibliography{references}

${SUB && addFiles ? `\\section*{Additional files}\n${addFiles}` : ''}
\\end{document}
`;
fs.writeFileSync(OUT, doc);
console.log(`wrote ${OUT}: ${fig} figures, ${tab} tables`);
